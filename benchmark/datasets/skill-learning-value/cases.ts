/**
 * Skill learning value eval: is a procedure better stored as a learned skill or as notes?
 *
 * Each case is a scripted session 1 that works a procedure out through real failures and
 * ends with the user confirming it, a session-2 task that needs the same procedure, the
 * ground-truth steps of session 2, and the checkpoints where a known pitfall waits.
 * See docs/designs/skill-learning-value-eval.md.
 *
 * Case data only. Editing anything here changes the case hash the runner records.
 */
import type { KodaXMessage } from '@kodax-ai/llm';

import { assistantCall, assistantText, toolResult, user } from '../feature-308-baseline/cases.js';

export type Tier = 'simple' | 'complex';

/** One ground-truth action of session 2 with its canned result. */
export interface Step {
  readonly tool: 'bash' | 'write' | 'edit';
  readonly input: Record<string, unknown>;
  readonly result: string;
}

export interface Checkpoint {
  /** Index into `steps` of the step the model must take next; earlier steps are history. */
  readonly step: number;
  /** Matches one serialized tool call (`{"name":...,"input":...}`) that takes the step. */
  readonly expect: RegExp;
  /** Matches when the model walks into the pitfall session 1 met. */
  readonly pitfall: RegExp;
  /** What the step is, for the blinded reviewer. */
  readonly label: string;
}

export interface ValueCase {
  readonly id: 's1' | 's2' | 'c1' | 'c2' | 'c3';
  readonly tier: Tier;
  readonly family: string;
  readonly sessionOne: readonly KodaXMessage[];
  readonly task: string;
  readonly steps: readonly Step[];
  readonly checkpoints: readonly Checkpoint[];
  /** Matches a first response that walks into any pitfall of this procedure (probe D). */
  readonly anyPitfall: RegExp;
  /** Matches a first response that takes the procedure's first step (probe D). */
  readonly firstStep: RegExp;
  /** Facts the stored procedure must carry, one per checkpoint (content fidelity, recorded only). */
  readonly facts: readonly RegExp[];
}

function failed(id: string, content: string): KodaXMessage {
  return { role: 'user', content: [{ type: 'tool_result', tool_use_id: id, content, is_error: true }] };
}

const bash = (command: string, result: string): Step => ({ tool: 'bash', input: { command }, result });

