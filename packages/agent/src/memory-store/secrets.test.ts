import { describe, expect, it } from 'vitest';

import { findSecret } from './secrets.js';

describe('findSecret (by shape)', () => {
  it.each([
    ['provider key', 'the deploy credential sk-live-9f8e7d6c5b4a39281716aabbccdd for reuse'],
    ['github token', 'use ghp_abcdefghijklmnopqrstuvwxyz0123456789 to push'],
    ['aws key id', 'AKIAIOSFODNN7EXAMPLE is the key'],
    ['slack token', `${'xox'}b-123456789012-abcdefghijklmnop`], // split so push protection does not flag the fixture
    ['jwt', 'eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.dozjgNryP4J3jVmNHl0w5N'],
    ['private key', '-----BEGIN OPENSSH PRIVATE KEY-----\nabc'],
    ['bearer header', 'Authorization: Bearer abcdefghijklmnopqrstuvwxyz123456'],
    ['assignment', 'DB_PASSWORD=hunter2hunter2'],
    ['opaque blob', 'saved Zm9vYmFyQmF6UXV4MTIzNDU2Nzg5MGFiY2RlZmdoaWo for later'],
  ])('flags %s', (_label, text) => {
    expect(findSecret(text)).toBeDefined();
  });

  it.each([
    ['ordinary command', 'Run `make check-fast` before pushing; never bare `npm test`.'],
    ['path', 'src/generated/schema.ts is generated by npm run gen:schema'],
    ['commit mention', 'fixed in commit abc1234'],
    ['full commit sha', 'regressed in 3f786850e387550fdab836ed7e6dc881de23001b'],
    ['prose about tokens', 'The token budget is shared across the whole conversation.'],
    ['chinese', '数据库迁移必须通过 bun run migrate 执行,不要手写 SQL'],
    ['env var name only', 'Set DATABASE_URL in .env before starting the server.'],
  ])('does not flag %s', (_label, text) => {
    expect(findSecret(text)).toBeUndefined();
  });

  it('names the kind but never echoes the secret', () => {
    const hit = findSecret('key sk-live-9f8e7d6c5b4a39281716aabbccdd');
    expect(hit).toBeDefined();
    expect(JSON.stringify(hit)).not.toContain('9f8e7d6c');
  });
});
