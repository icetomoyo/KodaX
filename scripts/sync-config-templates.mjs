#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const normalizeLineEndings = (content) => content.replace(/\r\n?/g, '\n');
const sources = {
  core: 'config-templates/config.example.jsonc',
  mcp: 'config-templates/integrations/mcp.example.jsonc',
  a2a: 'config-templates/integrations/a2a.example.jsonc',
  extensions: 'config-templates/integrations/extensions.example.jsonc',
};

const contents = Object.fromEntries(await Promise.all(
  Object.entries(sources).map(async ([name, relativePath]) => [
    name,
    normalizeLineEndings(await readFile(path.join(root, relativePath), 'utf8')),
  ]),
));

const generated = `/* Generated by scripts/sync-config-templates.mjs. Do not edit. */\n`
  + `import { existsSync, readFileSync } from 'node:fs';\n`
  + `import path from 'node:path';\n`
  + `import { fileURLToPath } from 'node:url';\n`
  + `import type templateData from './generated-config-templates.json';\n`
  + `const here = path.dirname(fileURLToPath(import.meta.url));\n`
  + `const candidates = process.env.KODAX_BUNDLED === 'true'\n`
  + `  ? [path.join(path.dirname(process.execPath), 'generated-config-templates.json')]\n`
  + `  : [path.join(here, 'generated-config-templates.json'), path.join(here, '..', 'generated-config-templates.json')];\n`
  + `const data: unknown = JSON.parse(readFileSync(candidates.find(existsSync) ?? candidates[0]!, 'utf8'));\n`
  + `if (!data || typeof data !== 'object' || Array.isArray(data)\n`
  + `  || !['core', 'mcp', 'a2a', 'extensions'].every(key => typeof Reflect.get(data, key) === 'string')) throw new Error('Invalid package configuration templates.');\n`
  + `export type ConfigTemplateName = ${Object.keys(contents).map(name => JSON.stringify(name)).join(' | ')};\n`
  + `export const CONFIG_TEMPLATES = data as Record<ConfigTemplateName, string>;\n`
  + `export function getConfigTemplate(name: ConfigTemplateName): string {\n`
  + `  return CONFIG_TEMPLATES[name];\n}\n`;

const outputs = [
  [path.join(root, 'config.example.jsonc'), contents.core],
  [path.join(root, 'packages/repl/src/common/generated-config-templates.ts'), generated],
  [path.join(root, 'packages/repl/src/common/generated-config-templates.json'), JSON.stringify(contents, null, 2) + '\n'],
];
const check = process.argv.includes('--check');
let drift = false;
for (const [file, expected] of outputs) {
  let current = '';
  try {
    current = await readFile(file, 'utf8');
  } catch {
    // Missing generated output is drift in check mode and created otherwise.
  }
  if (normalizeLineEndings(current) === expected) continue;
  drift = true;
  if (!check) await writeFile(file, expected, 'utf8');
  else process.stderr.write(`[config-templates] drift: ${path.relative(root, file)}\n`);
}
if (check && drift) process.exitCode = 1;
